import SwiftUI
import VoiceoverKit

/// Opens the sound suggestions. The model reads the captions, so there is nothing to suggest from until a
/// take is transcribed or a voiceover generated.
///
/// The sheet itself is presented by the editor: attached to a row of the form, it was dismissed whenever the
/// form rebuilt that row, halfway through a plan.
struct SoundIdeasSection: View {
    let model: EditorModel
    let onSuggest: () -> Void

    var body: some View {
        Section {
            Button("Suggest sounds", systemImage: "sparkles", action: onSuggest)
                .disabled(model.captions.isEmpty || model.isBusy)
        } footer: {
            Text(model.captions.isEmpty
                ? "Record a take or generate a voiceover, and Apple Intelligence will suggest sounds for what is said."
                : "Apple Intelligence reads what is said and suggests effects and music, on this device and for free.")
        }
        .onAppear { model.prewarmSoundIdeas() }
    }
}

/// The plan as it streams in. Nothing is spent until the user adds the effects or generates the music.
struct SoundIdeasSheet: View {
    let model: EditorModel
    let hasAPIKey: Bool
    @Environment(\.dismiss) private var dismiss
    /// Effects to generate, by their position in the plan. All of them once the plan is complete.
    @State private var picked: Set<SoundPlan.Effect.ID> = []

    private var ideas: SoundIdeas { model.soundIdeas }
    private var plan: SoundPlan { ideas.plan ?? SoundPlan() }

    var body: some View {
        NavigationStack {
            Form {
                if let failure = ideas.failure {
                    Section {
                        Label(failure, systemImage: "exclamationmark.triangle")
                        Button("Try again", systemImage: "arrow.clockwise") { model.suggestSounds() }
                    }
                } else if ideas.isPlanning, plan.effects.isEmpty {
                    Section {
                        HStack(spacing: 12) {
                            ProgressView()
                            Text("Reading what is said…")
                                .foregroundStyle(.secondary)
                        }
                    }
                }
                if !plan.effects.isEmpty {
                    effectsSection
                }
                if !plan.musicPrompt.isEmpty {
                    musicSection
                }
                if !ideas.isPlanning, ideas.failure == nil, ideas.plan != nil {
                    Section {
                        Button("Suggest again", systemImage: "arrow.clockwise") { model.suggestSounds() }
                    }
                }
            }
            .navigationTitle("Sound ideas")
            .navigationBarTitleDisplayMode(.inline)
            .toolbar {
                // System close and confirm icons: a worded button as long as "Add 3 effects" pushed the
                // title off centre. The count is still read out by VoiceOver.
                ToolbarItem(placement: .cancellationAction) {
                    Button(role: .close) { dismiss() }
                }
                ToolbarItem(placement: .confirmationAction) {
                    Button(role: .confirm) {
                        model.addEffects(plan.effects.filter { picked.contains($0.id) })
                        dismiss()
                    }
                    .accessibilityLabel(addTitle)
                    .disabled(ideas.isPlanning || picked.isEmpty || !hasAPIKey || model.activity != nil)
                }
            }
        }
        .onAppear { model.suggestSounds() }
        .onDisappear { ideas.cancel() }
        .onChange(of: ideas.isPlanning) { _, isPlanning in
            picked = isPlanning ? [] : Set(plan.effects.map(\.id))
        }
    }

    private var effectsSection: some View {
        Section {
            ForEach(plan.effects) { effect in
                Toggle(isOn: binding(for: effect.id)) {
                    VStack(alignment: .leading, spacing: 2) {
                        Text(effect.prompt)
                        Text("At \(seconds(effect.start)) s, \(seconds(effect.duration)) s long")
                            .font(.caption)
                            .foregroundStyle(.secondary)
                        if !effect.cue.isEmpty {
                            Text("“\(effect.cue)”")
                                .font(.caption)
                                .italic()
                                .foregroundStyle(.secondary)
                                .lineLimit(2)
                        }
                    }
                }
                .disabled(ideas.isPlanning)
            }
        } header: {
            Text("Effects")
        } footer: {
            Text("Each effect you add is generated by ElevenLabs and costs credits.")
        }
    }

    private var musicSection: some View {
        Section {
            Label(plan.musicPrompt, systemImage: "music.note")
            Button(musicTitle, systemImage: "wand.and.stars") {
                model.generateMusic(prompt: plan.musicPrompt)
                dismiss()
            }
            .disabled(ideas.isPlanning || !hasAPIKey || model.activity != nil)
        } header: {
            Text("Music")
        } footer: {
            if model.project.music != nil {
                Text("Replaces the current music.")
            }
        }
    }

    private var addTitle: String {
        String(localized: "Add \(picked.count) effects")
    }

    private var musicTitle: String {
        String(localized: "Generate music · \(Int(model.musicLength.rounded(.up))) s")
    }

    private func binding(for id: SoundPlan.Effect.ID) -> Binding<Bool> {
        Binding(
            get: { picked.contains(id) },
            set: { isOn in
                if isOn {
                    picked.insert(id)
                } else {
                    picked.remove(id)
                }
            }
        )
    }

    private func seconds(_ value: Double) -> String {
        value.formatted(.number.precision(.fractionLength(1)))
    }
}
